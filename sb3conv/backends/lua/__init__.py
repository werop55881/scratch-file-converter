"""Lua (LÖVE) backend: emit a LÖVE game directory (packed as .love).

Output layout::

    <out>/main.lua            generated scripts, MANIFEST require, SCRIPTS registration
    <out>/runtime.lua         copy of runtime_src.lua (LÖVE + LuaJIT only)
    <out>/manifest.lua        stage/sprite/monitor description as a Lua table module
    <out>/conf.lua            LÖVE window/module configuration (scale baked in)
    <out>/sb3_manifest.json   same manifest as JSON (round trip / tooling)
    <out>/assets/*            costumes and sounds extracted from the .sb3

Scripts are plain functions run as coroutines: every blocking action yields,
the scheduler resumes them once per frame. Conditions go through ``s_bool``
so Lua matches JavaScript truthiness.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

from sb3conv.backends.base import BackendSpec, EmitResult, OutputFile
from sb3conv.backends.lua.exprs import lua_str
from sb3conv.backends.lua.stmts import StatementEmitter
from sb3conv.backends.python import _manifest, _plan_assets, _route_fields, _script_language
from sb3conv.errors import BackendError
from sb3conv.sb3.model import Project
from sb3conv.sb3.procedures import find_procedures, procedure_by_script, procedure_map

RUNTIME_SOURCE = Path(__file__).with_name("runtime_src.lua")

# script-lang tags that emit under this backend (love is an alias for lua)
_ACCEPTED = ("lua", "love")

_IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")

_STAGE_W = 480
_STAGE_H = 360


def _is_ident(key: str) -> bool:
    return bool(_IDENT.match(key))


def _lua_literal(obj, level: int = 0) -> str:  # noqa: ANN001 - JSON-ish trees only
    """A Lua literal for a JSON-ish value (dict/list/str/num/bool/None)."""
    pad = "  " * level
    inner = "  " * (level + 1)
    if obj is None:
        return "nil"
    if isinstance(obj, bool):
        return "true" if obj else "false"
    if isinstance(obj, (int, float)):
        if obj != obj:  # NaN
            return "(0/0)"
        if obj == float("inf"):
            return "math.huge"
        if obj == float("-inf"):
            return "-math.huge"
        if float(obj).is_integer() and abs(obj) < 1e15:
            return str(int(obj))
        return repr(float(obj))
    if isinstance(obj, str):
        return lua_str(obj)
    if isinstance(obj, dict):
        items = []
        for key, value in obj.items():
            if value is None:
                continue
            name = str(key)
            rendered = _lua_literal(value, level + 1)
            if _is_ident(name):
                items.append(f"{inner}{name} = {rendered}")
            else:
                items.append(f"{inner}[{lua_str(name)}] = {rendered}")
        if not items:
            return "{}"
        return "{\n" + ",\n".join(items) + ",\n" + pad + "}"
    if isinstance(obj, (list, tuple)):
        if not obj:
            return "{}"
        scalars = all(
            v is None or isinstance(v, (int, float, str, bool)) for v in obj
        )
        rendered = [_lua_literal(v, level + 1) for v in obj]
        if scalars:
            return "{ " + ", ".join(rendered) + " }"
        body = ",\n".join(f"{inner}{item}" for item in rendered)
        return "{\n" + body + ",\n" + pad + "}"
    raise TypeError(f"cannot emit Lua literal for {type(obj).__name__}")


def _main_source(functions: list[str], regs: list[tuple[str, str, dict, str]], function_names: list[str]) -> str:
    lines = [
        "-- Converted from Scratch by sb3conv. Run with: love .",
        'require("runtime")',
        "",
        'local MANIFEST = require("manifest")',
        "",
    ]
    if function_names:
        lines.append("local " + ", ".join(function_names))
        lines.append("")
    for source in functions:
        lines.append(source)
        lines.append("")
    lines.append("local SCRIPTS = {")
    for sprite, hat, fields, fn_name in regs:
        lines.append(
            f"  ScriptReg({lua_str(sprite)}, {lua_str(hat)}, {_lua_literal(fields)}, {fn_name}),"
        )
    lines.append("}")
    lines.append("")
    lines.append("run(SCRIPTS, MANIFEST)")
    lines.append("")
    return "\n".join(lines)


def _conf_source(name: str, scale: int) -> str:
    width = _STAGE_W * max(1, scale)
    height = _STAGE_H * max(1, scale)
    identity = re.sub(r"[^\w-]+", "_", name)[:64] or "sb3-project"
    return f"""\
-- LÖVE configuration (generated by sb3conv)
function love.conf(t)
  t.identity = {lua_str(identity)}
  t.console = false
  t.window.title = {lua_str(name)}
  t.window.width = {width}
  t.window.height = {height}
  t.window.resizable = false
  t.window.vsync = 1
  t.modules.joystick = false
  t.modules.physics = false
  t.modules.touch = false
  t.modules.video = false
end
"""


def _check_lua(sources: dict[str, str]) -> None:
    """Syntax-check generated Lua with luac/lua/luajit when one is on PATH."""
    luac = shutil.which("luac")
    lua = shutil.which("lua") or shutil.which("luajit")
    if not luac and not lua:
        return
    with tempfile.TemporaryDirectory(prefix="sb3conv-lua-") as tmp:
        root = Path(tmp)
        paths: list[Path] = []
        for name, source in sources.items():
            path = root / name
            path.write_text(source, encoding="utf-8")
            paths.append(path)
        for path in paths:
            if luac:
                proc = subprocess.run(
                    [luac, "-p", str(path)], capture_output=True, text=True, check=False
                )
            else:
                proc = subprocess.run(
                    [lua, "-e", f"assert(loadfile({json.dumps(str(path))}))"],
                    capture_output=True,
                    text=True,
                    check=False,
                )
            if proc.returncode != 0:
                detail = (proc.stderr or proc.stdout).strip()
                raise BackendError(f"generated {path.name} is not valid Lua:\n{detail}")


def emit_lua(project: Project, options: dict) -> EmitResult:
    warnings: list[str] = []

    def warn(message: str) -> None:
        warnings.append(message)

    overrides = dict(options.get("script_lang") or {})
    assets: dict[str, bytes] = dict(options.get("assets") or {})

    functions: list[str] = []
    function_names: list[str] = []
    regs: list[tuple[str, str, dict, str]] = []
    script_languages: dict[str, str] = {}

    procedures = find_procedures(project)
    proc_map = procedure_map(procedures)
    proc_script = procedure_by_script(procedures)

    for index, script in enumerate(project.all_scripts()):
        procedure = proc_script.get(script.script_id)
        is_definition = script.hat.opcode == "procedures_definition"
        language = _script_language(script, overrides, default="lua")
        script_languages[script.script_id] = language
        if not is_definition and language not in _ACCEPTED:
            warn(
                f"script at {script.target.name}:{round(script.hat.y)} is tagged "
                f"{language!r}; the lua backend skipped it"
            )
            continue
        function_name = procedure.fn_name if procedure else f"script_{index}"
        source = StatementEmitter(
            project, script, warn, procedures=proc_map, procedure=procedure
        ).emit_function(function_name)
        if source is None:
            continue
        functions.append(source)
        function_names.append(function_name)
        if is_definition:
            continue  # custom blocks are called, not registered as hat routes
        regs.append(
            (script.target.name, script.hat.opcode, _route_fields(project, script), function_name)
        )

    plan = _plan_assets(project, assets, warn, svg_policy="rasterize", svg_runtime="LÖVE")
    manifest_obj = _manifest(project, options, plan)
    manifest_json = json.dumps(manifest_obj, indent=2, ensure_ascii=False)
    name = str(manifest_obj["name"])
    scale = int(manifest_obj.get("scale", 2))
    main_source = _main_source(functions, regs, function_names)
    runtime_source = RUNTIME_SOURCE.read_text(encoding="utf-8")
    manifest_lua = "-- Project manifest (generated by sb3conv)\nreturn " + _lua_literal(
        manifest_obj
    ) + "\n"
    conf_source = _conf_source(name, scale)
    _check_lua(
        {
            "main.lua": main_source,
            "runtime.lua": runtime_source,
            "manifest.lua": manifest_lua,
            "conf.lua": conf_source,
        }
    )

    files = [
        OutputFile(path="main.lua", content=main_source),
        OutputFile(path="runtime.lua", content=runtime_source),
        OutputFile(path="manifest.lua", content=manifest_lua),
        OutputFile(path="conf.lua", content=conf_source),
        OutputFile(path="sb3_manifest.json", content=manifest_json),
        *plan.files,
    ]
    return EmitResult(
        files=files,
        warnings=warnings,
        entrypoint="main.lua",
        script_languages=script_languages,
    )


SPEC = BackendSpec(
    name="lua",
    label="Lua (LÖVE)",
    file_extension=".lua",
    emitter=emit_lua,
)
