#> Godot 4 backend: emit a Godot project (open in the editor and run).
#
#> Output layout::
#
#>     <out>/project.godot    Godot project (window, stretch, main scene)
#>     <out>/main.tscn        root scene attaching runtime.gd
#>     <out>/runtime.gd       copy of runtime_src.gd (await-based scheduler)
#>     <out>/scratch.gd       copy of scratch.gd (Scratch operator semantics)
#>     <out>/scripts.gd       generated scripts + registrations()
#>     <out>/manifest.json    stage/sprite/monitor description
#>     <out>/sb3_manifest.json  same manifest (round trip / tooling)
#>     <out>/assets/*         costumes and sounds (SVG kept: Godot imports it)
#
#> Scripts are GDScript coroutines: every blocking action awaits ``rt.tick``
#> (one signal per logical frame); conditions go through ``Scratch.s_bool``
#> so Godot matches JavaScript truthiness.
from __future__ import annotations

import json
import os
import re
import shutil
from pathlib import Path

from sb3conv.backends.base import BackendSpec, EmitResult, OutputFile
from sb3conv.backends.godot.stmts import StatementEmitter, godot_str
from sb3conv.backends.python import _manifest, _plan_assets, _route_fields, _script_language
from sb3conv.sb3.model import Project
from sb3conv.sb3.procedures import find_procedures, procedure_by_script, procedure_map

RUNTIME_SOURCE = Path(__file__).with_name("runtime_src.gd")
SCRATCH_SOURCE = Path(__file__).with_name("scratch.gd")

# script-lang tags that emit under this backend
_ACCEPTED = ("godot", "gdscript")

_STAGE_W = 480
_STAGE_H = 360


def find_godot() -> str | None:
    """Locate the Godot 4 editor: $GODOT, PATH, then the portable ~/godotsdk."""
    override = os.environ.get("GODOT")
    if override and Path(override).exists():
        return override
    for name in ("godot", "godot4", "Godot"):
        found = shutil.which(name)
        if found:
            return found
    for name in ("godot.exe", "godot"):
        fallback = Path.home() / "godotsdk" / name
        if fallback.exists():
            return str(fallback)
    return None


def _is_ident(key: str) -> bool:
    return bool(re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z").match(key))


def _gd_literal(obj, level: int = 0) -> str:  # noqa: ANN001 - JSON-ish trees only
    """A GDScript literal for a JSON-ish value (dict/list/str/num/bool/None)."""
    pad = "\t" * level
    inner = "\t" * (level + 1)
    if obj is None:
        return "null"
    if isinstance(obj, bool):
        return "true" if obj else "false"
    if isinstance(obj, (int, float)):
        if obj != obj:  # NaN
            return "NAN"
        if obj == float("inf"):
            return "INF"
        if obj == float("-inf"):
            return "-INF"
        if float(obj).is_integer() and abs(obj) < 1e15:
            return f"{int(obj)}.0" if isinstance(obj, float) else f"{obj}.0"
        return repr(float(obj))
    if isinstance(obj, str):
        return godot_str(obj)
    if isinstance(obj, dict):
        items = []
        for key, value in obj.items():
            if value is None:
                continue
            items.append(f"{inner}{godot_str(str(key))}: {_gd_literal(value, level + 1)}")
        if not items:
            return "{}"
        return "{\n" + ",\n".join(items) + ",\n" + pad + "}"
    if isinstance(obj, (list, tuple)):
        if not obj:
            return "[]"
        rendered = [_gd_literal(v, level + 1) for v in obj]
        return "[" + ", ".join(rendered) + "]"
    raise TypeError(f"cannot emit GDScript literal for {type(obj).__name__}")


def _scripts_source(
    functions: list[str],
    regs: list[tuple[str, str, dict, str]],
) -> str:
    lines = [
        "#> Generated Scratch scripts (sb3conv).",
        "extends RefCounted",
        "",
    ]
    for source in functions:
        lines.append(source)
        lines.append("")
    lines.append("func registrations() -> Array:")
    lines.append("\treturn [")
    for sprite, hat, fields, fn_name in regs:
        lines.append(
            "\t\t{"
            f'"sprite": {godot_str(sprite)}, '
            f'"hat": {godot_str(hat)}, '
            f'"fields": {_gd_literal(fields)}, '
            f'"fn": {godot_str(fn_name)}'
            "},"
        )
    lines.append("\t]")
    lines.append("")
    return "\n".join(lines)


def _project_source(name: str, scale: int) -> str:
    width = _STAGE_W * max(1, scale)
    height = _STAGE_H * max(1, scale)
    return f"""\
; Godot project (generated by sb3conv)
config_version=5

[application]

config/name={godot_str(name)}
run/main_scene="res://main.tscn"

[display]

window/size/viewport_width=480
window/size/viewport_height=360
window/size/window_width_override={width}
window/size/window_height_override={height}
window/stretch/mode="canvas_items"

[rendering]

renderer/rendering_method="gl_compatibility"
renderer/rendering_method.mobile="gl_compatibility"
"""


_MAIN_SCENE = """\
[gd_scene load_steps=2 format=3]

[ext_resource type="Script" path="res://runtime.gd" id="1"]

[node name="Main" type="Node2D"]
script = ExtResource("1")
"""


_GITIGNORE = """\
.godot/
*.import
"""


def emit_godot(project: Project, options: dict) -> EmitResult:
    warnings: list[str] = []

    def warn(message: str) -> None:
        warnings.append(message)

    overrides = dict(options.get("script_lang") or {})
    assets: dict[str, bytes] = dict(options.get("assets") or {})

    functions: list[str] = []
    regs: list[tuple[str, str, dict, str]] = []
    script_languages: dict[str, str] = {}

    procedures = find_procedures(project)
    proc_map = procedure_map(procedures)
    proc_script = procedure_by_script(procedures)

    for index, script in enumerate(project.all_scripts()):
        procedure = proc_script.get(script.script_id)
        is_definition = script.hat.opcode == "procedures_definition"
        language = _script_language(script, overrides, default="godot")
        script_languages[script.script_id] = language
        if not is_definition and language not in _ACCEPTED:
            warn(
                f"script at {script.target.name}:{round(script.hat.y)} is tagged "
                f"{language!r}; the godot backend skipped it"
            )
            continue
        function_name = procedure.fn_name if procedure else f"script_{index}"
        source = StatementEmitter(
            project, script, warn, procedures=proc_map, procedure=procedure
        ).emit_function(function_name)
        if source is None:
            continue
        functions.append(source)
        if is_definition:
            continue  # custom blocks are called, not registered as hat routes
        regs.append(
            (script.target.name, script.hat.opcode, _route_fields(project, script), function_name)
        )

    plan = _plan_assets(project, assets, warn)  # SVG passthrough: Godot imports it
    manifest_obj = _manifest(project, options, plan)
    manifest_json = json.dumps(manifest_obj, indent=2, ensure_ascii=False)
    name = str(manifest_obj["name"])
    scale = int(manifest_obj.get("scale", 2))
    scripts_source = _scripts_source(functions, regs)
    runtime_source = RUNTIME_SOURCE.read_text(encoding="utf-8")
    scratch_source = SCRATCH_SOURCE.read_text(encoding="utf-8")
    project_source = _project_source(name, scale)

    files = [
        OutputFile(path="project.godot", content=project_source),
        OutputFile(path="main.tscn", content=_MAIN_SCENE),
        OutputFile(path="runtime.gd", content=runtime_source),
        OutputFile(path="scratch.gd", content=scratch_source),
        OutputFile(path="scripts.gd", content=scripts_source),
        OutputFile(path="manifest.json", content=manifest_json),
        OutputFile(path="sb3_manifest.json", content=manifest_json),
        OutputFile(path=".gitignore", content=_GITIGNORE),
        *plan.files,
    ]
    return EmitResult(
        files=files,
        warnings=warnings,
        entrypoint="project.godot",
        script_languages=script_languages,
    )


SPEC = BackendSpec(
    name="godot",
    label="Godot 4 (GDScript)",
    file_extension=".gd",
    emitter=emit_godot,
)
